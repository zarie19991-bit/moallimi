// Keep existing page styles but remove remote font imports from the teacher workspace.
// Originals remain available to other platform pages. Generated assets share the same root URLs.
import fs from 'node:fs';
export function buildWorkspaceStyles(){
 for(const name of ['styles.css','create.css','stitch-platform-theme.css','homepage.css','analysis-print-scale-95.css']){
  const source=fs.readFileSync(name,'utf8');
  const css=source.replace(/@import\s+url\(['"]?https:\/\/fonts\.googleapis\.com\/[^)]*\)\s*;\s*/g,match=>name==='analysis-print-scale-95.css'?match.trim().replace(/\)\s*;$/,') print;')+'\n':'');
  fs.writeFileSync('workspace-'+name,'/* Generated by build-workspace-styles.mjs; edit the original stylesheet. */\n'+css);
 }
}
buildWorkspaceStyles();
