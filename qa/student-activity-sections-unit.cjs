const fs=require('node:fs'),assert=require('node:assert/strict'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const file=fs.readFileSync(path.join(root,'lugati-student-adaptive.js'),'utf8');

assert.match(file,/tab:'journeys'/);
const nav=file.slice(file.indexOf('function nav()'),file.indexOf('function navTone'));
for(const id of ['journeys','remedial','growth','competition'])assert.match(nav,new RegExp("'"+id+"'"));
assert.doesNotMatch(nav,/'tasks'/);
assert.doesNotMatch(nav,/'progress'/);
assert.match(file,/function journeys\(\)/);
assert.match(file,/function remedial\(\)/);
assert.match(file,/function growth\(\)/);
assert.match(file,/function competition\(\)/);
assert.match(file,/id="readingJourneyTaskMount"/);
assert.match(file,/id="studentPrimaryMission"/);
assert.match(file,/id="teacherRemedialTaskMount"/);
assert.match(file,/id="teacherGrowthTaskMount"/);
assert.match(file,/id="lugatiCompetitionMount"/);
assert.match(file,/rows\.filter\(t=>t\.tier==='remedial'\)/);
assert.match(file,/rows\.filter\(t=>t\.tier==='reinforcement'\)/);
assert.match(file,/rows\.filter\(t=>t\.tier==='enrichment'\)/);
assert.match(file,/const views=\{journeys,remedial,growth,competition\}/);
assert.match(file,/S\.tab==='remedial'\|\|S\.tab==='growth'/);
assert.match(file,/studentTodayPulse/);
assert.match(file,/studentNextAction/);
assert.match(file,/مهامي العلاجية/);
assert.match(file,/التعزيز والإثراء/);
assert.match(file,/lugatiCompetitionMount/);
assert.doesNotMatch(file,/function home\(\)/);
assert.doesNotMatch(file,/function progress\(\)/);
assert.match(file,/grid-cols-4/);
assert.match(file,/aria-current/);
console.log('PASS: student workspace has four isolated activity sections with responsive navigation and tier separation.');
